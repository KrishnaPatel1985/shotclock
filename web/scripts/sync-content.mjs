// Copies the official sources (../docs/state, ../docs/city), the demo files (../demo) and the saved
// accuracy-test result (../backtest/last-result.json) into lib/generated/content.ts, so the Vercel
// functions carry exactly the same library as the Streamlit app. Runs before every build.
// If the parent folders are missing (e.g. a build that only sees web/), the committed file is kept.
import { readFileSync, readdirSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "..", "..");
const out = join(here, "..", "lib", "generated", "content.ts");

if (!existsSync(join(repo, "docs", "state"))) {
  console.log("sync-content: ../docs not found; keeping the committed lib/generated/content.ts");
  process.exit(0);
}

const sources = [];
for (const kind of ["state", "city"]) {
  const dir = join(repo, "docs", kind);
  for (const name of readdirSync(dir).sort()) {
    if (!/\.(md|txt)$/i.test(name) || name.toLowerCase() === "readme.md") continue;
    sources.push({ kind, name, text: readFileSync(join(dir, name), "utf8") });
  }
}

const demo = {
  project: readFileSync(join(repo, "demo", "sample-project.md"), "utf8"),
  letter: readFileSync(join(repo, "demo", "sample-comment-letter.md"), "utf8"),
};
const backtestPath = join(repo, "backtest", "last-result.json");
const backtest = existsSync(backtestPath) ? JSON.parse(readFileSync(backtestPath, "utf8")) : null;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "// GENERATED by scripts/sync-content.mjs from ../docs, ../demo and ../backtest. Do not edit.\n" +
    `export const SOURCES: { kind: "state" | "city"; name: string; text: string }[] = ${JSON.stringify(sources)};\n` +
    `export const DEMO: { project: string; letter: string } = ${JSON.stringify(demo)};\n` +
    `// eslint-disable-next-line @typescript-eslint/no-explicit-any\nexport const BACKTEST: any = ${JSON.stringify(backtest)};\n`,
);
console.log(`sync-content: ${sources.length} sources, demo files, backtest ${backtest ? "yes" : "no"} -> ${out}`);
